export function normalizeCountryName(value: string) {
  return value
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");
}

export function countryNameToCode(name: string): string | null {
  return countryNameToIsoCode[normalizeCountryName(name)] ?? null;
}
